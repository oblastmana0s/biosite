function attachLinkItemEvents() {
  const container = document.getElementById("editableLinksContainer");
  if (!container) return;

  container.querySelectorAll("[data-move-up]").forEach(btn => {
    btn.onclick = (e) => {
      const idx = parseInt(e.currentTarget.getAttribute("data-move-up"));
      if (idx > 0) {
        const temp = appData.links[idx];
        appData.links[idx] = appData.links[idx - 1];
        appData.links[idx - 1] = temp;
        saveBioData();
        renderApp();
        renderEditableLinksList();
        sfx.playPop();
      }
    };
  });

  container.querySelectorAll("[data-move-down]").forEach(btn => {
    btn.onclick = (e) => {
      const idx = parseInt(e.currentTarget.getAttribute("data-move-down"));
      if (idx < appData.links.length - 1) {
        const temp = appData.links[idx];
        appData.links[idx] = appData.links[idx + 1];
        appData.links[idx + 1] = temp;
        saveBioData();
        renderApp();
        renderEditableLinksList();
        sfx.playPop();
      }
    };
  });

  container.querySelectorAll("[data-delete-link]").forEach(btn => {
    btn.onclick = (e) => {
      const idx = parseInt(e.currentTarget.getAttribute("data-delete-link"));
      if (confirm(`Bạn có chắc muốn xóa liên kết "${appData.links[idx].title}"?`)) {
        appData.links.splice(idx, 1);
        saveBioData();
        renderApp();
        renderEditableLinksList();
        showToast("Đã xóa liên kết");
        sfx.playPop();
      }
    };
  });

  container.querySelectorAll(".link-edit-title").forEach(inp => {
    inp.oninput = (e) => {
      const idx = parseInt(e.target.getAttribute("data-idx"));
      appData.links[idx].title = e.target.value;
      saveBioData();
      renderApp();
    };
  });

  container.querySelectorAll(".link-edit-url").forEach(inp => {
    inp.oninput = (e) => {
      const idx = parseInt(e.target.getAttribute("data-idx"));
      appData.links[idx].url = e.target.value;
      saveBioData();
      renderApp();
    };
  });

  container.querySelectorAll(".link-edit-icon").forEach(sel => {
    sel.onchange = (e) => {
      const idx = parseInt(e.target.getAttribute("data-idx"));
      const newIcon = e.target.value;
      appData.links[idx].icon = newIcon;
      if (BRAND_COLORS[newIcon]) {
        appData.links[idx].iconColor = BRAND_COLORS[newIcon];
      }
      saveBioData();
      renderApp();
      renderEditableLinksList();
      sfx.playPop();
    };
  });

  container.querySelectorAll(".link-anim-select").forEach(sel => {
    sel.onchange = (e) => {
      const idx = parseInt(e.target.getAttribute("data-idx"));
      appData.links[idx].iconAnim = e.target.value;
      saveBioData();
      renderApp();
      sfx.playPop();
    };
  });

  // Custom Icon File Upload (preserves full GIF & WebP animation frames)
  container.querySelectorAll(".link-custom-icon-file").forEach(input => {
    input.onchange = (e) => {
      const idx = parseInt(e.target.getAttribute("data-idx"));
      const file = e.target.files[0];
      if (!file) return;

      const isAnimatedOrVector = file.type === "image/gif" || 
                                 file.type === "image/webp" || 
                                 file.type.includes("svg") || 
                                 file.name.toLowerCase().endsWith(".gif") || 
                                 file.name.toLowerCase().endsWith(".svg") ||
                                 file.name.toLowerCase().endsWith(".webp");

      const reader = new FileReader();
      reader.onload = (event) => {
        if (isAnimatedOrVector || file.size < 300 * 1024) {
          appData.links[idx].customIcon = event.target.result;
          saveBioData();
          renderApp();
          renderEditableLinksList();
          showToast(`Đã đổi icon/GIF cho "${appData.links[idx].title}"`);
          sfx.playPop();
          return;
        }

        const img = new Image();
        img.onload = () => {
          const maxDim = 128;
          let w = img.width;
          let h = img.height;
          if (w > maxDim || h > maxDim) {
            if (w > h) {
              h = Math.round((h * maxDim) / w);
              w = maxDim;
            } else {
              w = Math.round((w * maxDim) / h);
              h = maxDim;
            }
          }
          const canvas = document.createElement("canvas");
          canvas.width = w;
          canvas.height = h;
          const ctx = canvas.getContext("2d");
          ctx.drawImage(img, 0, 0, w, h);
          const optimizedDataUrl = canvas.toDataURL("image/png");

          appData.links[idx].customIcon = optimizedDataUrl;
          saveBioData();
          renderApp();
          renderEditableLinksList();
          showToast(`Đã đổi icon riêng cho "${appData.links[idx].title}"`);
          sfx.playPop();
        };
        img.onerror = () => {
          appData.links[idx].customIcon = event.target.result;
          saveBioData();
          renderApp();
          renderEditableLinksList();
          showToast(`Đã đổi icon riêng cho "${appData.links[idx].title}"`);
          sfx.playPop();
        };
        img.src = event.target.result;
      };
      reader.readAsDataURL(file);
    };
  });

  // Remove Custom Icon
  container.querySelectorAll("[data-remove-custom-icon]").forEach(btn => {
    btn.onclick = (e) => {
      const idx = parseInt(e.currentTarget.getAttribute("data-remove-custom-icon"));
      appData.links[idx].customIcon = null;
      saveBioData();
      renderApp();
      renderEditableLinksList();
      showToast("Đã chuyển về icon mặc định");
      sfx.playPop();
    };
  });

  container.querySelectorAll(".link-edit-color").forEach(inp => {
    inp.oninput = (e) => {
      const idx = parseInt(e.target.getAttribute("data-idx"));
      appData.links[idx].iconColor = e.target.value;
      saveBioData();
      renderApp();
    };
  });

  container.querySelectorAll(".link-edit-sub").forEach(inp => {
    inp.oninput = (e) => {
      const idx = parseInt(e.target.getAttribute("data-idx"));
      appData.links[idx].subtitle = e.target.value;
      saveBioData();
      renderApp();
    };
  });

  container.querySelectorAll(".link-edit-badge").forEach(inp => {
    inp.oninput = (e) => {
      const idx = parseInt(e.target.getAttribute("data-idx"));
      appData.links[idx].badge = e.target.value.toUpperCase();
      saveBioData();
      renderApp();
    };
  });
}

